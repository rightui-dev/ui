import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHighlighter, type ThemedToken } from 'shiki';

// Adapted from the shadcn Code Block demo; see THIRD_PARTY_NOTICES.md.
const code = `import { streamText } from "ai"

export async function POST(request: Request) {
  const { messages } = await request.json()

  const result = streamText({
    model: "anthropic/claude-sonnet-4.5",
    system: "You are a helpful assistant. Answer in one short paragraph.",
    messages,
  })

  return result.toUIMessageStreamResponse()
}`;

function tone(token: ThemedToken): string {
  const scopes = token.explanation?.flatMap(part => part.scopes.map(scope => scope.scopeName)) ?? [];
  const has = (pattern: RegExp) => scopes.some(scope => pattern.test(scope));
  if (has(/^comment\./)) return 'comment';
  if (has(/^string\.|^punctuation\.definition\.string/)) return 'string';
  if (has(/^entity\.name\.function|^support\.function/)) return 'function';
  if (has(/^entity\.name\.(type|class)|^support\.type/)) return 'type';
  if (has(/^constant\.(numeric|language)/)) return 'number';
  if (has(/^keyword\.|^storage\./)) return 'keyword';
  if (has(/^variable\.other\.(property|object\.property)|^meta\.object-literal\.key/)) return 'property';
  return 'plain';
}

const highlighter = await createHighlighter({ themes: ['github-light'], langs: ['typescript'] });
try {
  const tokens = highlighter.codeToTokens(code, { lang: 'typescript', theme: 'github-light', includeExplanation: true }).tokens;
  if (tokens.map(line => line.map(token => token.content).join('')).join('\n') !== code) {
    throw new Error('Highlighting must preserve every source character.');
  }
  const lines = tokens.map((line, index) => {
    const spans = line.map(token => `CodeToken(text=${JSON.stringify(token.content)}, tone=${JSON.stringify(tone(token))})`);
    return `fn codeBlockDemoLine${index}(): CodeLine = CodeLine(tokens=[${spans.join(', ')}], variant="${index >= 5 && index <= 9 ? 'highlighted' : 'default'}")`;
  });
  const output = '// Generated by bun tools/generate-code-block.ts using Shiki.\n' +
    'use CodeToken, CodeLine from "@rightui/ui"\n\n' +
    `fn codeBlockDemoCode(): string = ${JSON.stringify(code)}\n\n` + lines.join('\n') + '\n\n' +
    `fn codeBlockDemoLines(): CodeLine[] = [${tokens.map((_, index) => `codeBlockDemoLine${index}()`).join(', ')}]\n`;
  const path = resolve(import.meta.dir, '../examples/code-block-data.contract');
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== output) throw new Error('Code Block highlighting is stale; run bun tools/generate-code-block.ts.');
  } else {
    writeFileSync(path, output);
  }
  console.log(`Code Block: ${tokens.length} highlighted lines; source text preserved.`);
} finally {
  highlighter.dispose();
}
